// Generates per-target string tables from i18n/strings.json (the only file to edit).
//   core/src/strings.json                        — used by Chrome + VS Code via @salat/core
//   desktop/resources/translations.json          — used by the Qt Tr singleton
//   android/app/src/main/res/values*/strings.xml — Android resources ({name} → %1$s … in key order)
//   vscode/package.nls*.json                      — command titles for the Marketplace / command palette
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';

const master = JSON.parse(readFileSync('i18n/strings.json', 'utf8'));
delete master._comment;
const LANGS = ['en', 'ar', 'de'];

function write(path, content) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  console.log(path);
}

// Sanity: every key has every language and the same placeholders.
for (const [key, v] of Object.entries(master)) {
  const ph = (s) => [...s.matchAll(/\{(\w+)\}/g)].map((m) => m[1]).sort().join(',');
  for (const l of LANGS) {
    if (typeof v[l] !== 'string' || !v[l]) throw new Error(`${key}: missing ${l}`);
    if (ph(v[l]) !== ph(v.en)) throw new Error(`${key}: placeholder mismatch in ${l}`);
  }
}

// 1. core + Qt: same shape { key: { en, ar, de } }
write('core/src/strings.json', JSON.stringify(master, null, 2) + '\n');
write('desktop/resources/translations.json', JSON.stringify(master) + '\n');

// 2. Android: res/values(-ar|-de)/strings.xml
const androidName = (key) => key.replace(/\./g, '_');
const xmlEscape = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/'/g, "\\'").replace(/"/g, '\\"');
const toAndroid = (s, order) => {
  let out = xmlEscape(s).replace(/%/g, '%%');
  order.forEach((name, i) => { out = out.replaceAll(`{${name}}`, `%${i + 1}$s`); });
  return out;
};
for (const l of LANGS) {
  const lines = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by tools/export_i18n.mjs from i18n/strings.json. Do not edit. -->', '<resources>'];
  for (const [key, v] of Object.entries(master)) {
    const order = [...new Set([...v.en.matchAll(/\{(\w+)\}/g)].map((m) => m[1]))];
    const attrs = order.length ? '' : ' translatable="true"';
    lines.push(`    <string name="${androidName(key)}"${attrs}>${toAndroid(v[l], order)}</string>`);
  }
  lines.push('</resources>', '');
  write(`android/app/src/main/res/values${l === 'en' ? '' : '-' + l}/strings.xml`, lines.join('\n'));
}
// Placeholder order per key, for Kotlin callers (documentation only).
const orders = Object.fromEntries(
  Object.entries(master)
    .map(([k, v]) => [androidName(k), [...new Set([...v.en.matchAll(/\{(\w+)\}/g)].map((m) => m[1]))]])
    .filter(([, o]) => o.length),
);
write('android/app/placeholders.txt', 'Placeholder order for formatted strings (generated):\n' + Object.entries(orders).map(([k, o]) => `${k}: ${o.join(', ')}`).join('\n') + '\n');

// 3. VS Code: package.nls.json (+ ar, de) for command titles
const nls = (l) => JSON.stringify({
  'cmd.showTimes': master['vscode.showTimes'][l],
  'cmd.setCity': master['vscode.setCity'][l],
  'cmd.openSettings': master['vscode.openSettings'][l],
}, null, 2) + '\n';
write('vscode/package.nls.json', nls('en'));
write('vscode/package.nls.ar.json', nls('ar'));
write('vscode/package.nls.de.json', nls('de'));
